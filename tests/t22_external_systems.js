'use strict';
const assert=require('node:assert/strict');
const fs=require('node:fs');
const vm=require('node:vm');
const source=fs.readFileSync('tools/external-systems.js','utf8');
const context={window:{},matchMedia:()=>({matches:false})};
vm.runInNewContext(source,context);
const gen=context.window.SF_EXTERNAL_SYSTEMS.generate;
const a=gen({id:'123456789',name:'TEST SYSTEM'});
const b=gen({id:'123456789',name:'TEST SYSTEM'});
const c=gen({id:'987654321',name:'OTHER SYSTEM'});
assert.deepEqual(JSON.parse(JSON.stringify(a)),JSON.parse(JSON.stringify(b)),'same ID must generate identical system');
assert.notEqual(a.seed,c.seed,'different IDs should produce different seeds');
assert.ok(a.planets.length>=2&&a.planets.length<=8,'planet count must stay in bounds');
for(let i=1;i<a.planets.length;i++)assert.ok(a.planets[i].orbit>a.planets[i-1].orbit,'planet orbits must be strictly ordered');
assert.ok(a.planets.every(p=>p.radius>0&&p.period>0),'planet dimensions and periods must be positive');
assert.ok(a.star.class&&a.star.color&&a.star.temp,'star classification must be complete');
assert.ok(a.station===null||a.station.orbit>0,'station orbit must be valid');
assert.ok(a.belt===null||a.belt.count>0,'asteroid belt instance count must be positive');
console.log('External system deterministic generation: PASS');
